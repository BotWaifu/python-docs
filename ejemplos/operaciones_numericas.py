# Ejemplos númericos
a = 10
b = 3

print(a + b)  # 13
print(a - b)  # 7
print(a * b)  # 30
print(a / b)  # 3.33

print(7 % 2)
print(10 % 5)

x = 5
print(-x)
print(-(-5))

x = 3
print(+x)

print(abs(-4))
print(abs(4))

print(int(3.9))
print(float(5))

z = complex(2, 3)
print(z)

print((2 + 3j).conjugate())
print(divmod(9, 4))
print(pow(2, 3))
print(2 ** 3)
print(9 ** 0.5)
